import json, sys, os

sys.stdout.reconfigure(encoding='utf-8')
base = 'F:/Project-F/Assets/Resources/Data/Dialogues'

def load(fname):
    with open(os.path.join(base, fname), 'r', encoding='utf-8-sig') as f:
        return json.load(f)

def save(fname, data):
    with open(os.path.join(base, fname), 'w', encoding='utf-8-sig') as f:
        json.dump(data, f, ensure_ascii=False, indent=4)

# ============================================================
# Fix 1: 리모델링 기간 "1년" → "수개월" (기한 모순)
# ============================================================
data = load('ch0_origin.json')
for n in data['nodes']:
    if '1년에 걸친 리모델링 끝에' in n.get('text', ''):
        n['text'] = n['text'].replace('1년에 걸친 리모델링 끝에', '수개월에 걸친 리모델링 끝에')
        print('Fix 1: Remodeling period 1년 -> 수개월 (node ' + str(n['id']) + ')')

# ============================================================
# Fix 2: "로펌 취직을 포기하고" → "로펌을 그만두고" (이미 재직중)
